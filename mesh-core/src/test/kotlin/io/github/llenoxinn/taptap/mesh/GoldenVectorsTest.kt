package io.github.llenoxinn.taptap.mesh

import org.junit.jupiter.api.Tag
import java.io.File
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

/**
 * Golden vectors for other implementations (the M3 Deno server). Sealing uses a random ephemeral
 * key, so the file stores sealed output and checks opening, not byte-identical re-sealing.
 */
class GoldenVectorsTest {
    private val file = File("src/test/resources/vectors/envelope-v1.txt")

    private val deviceSeed = seed(0)
    private val signSeed = seed(32)
    private val boxSeed = seed(64)
    private val keyId = 1

    private val sosMax = SosRequest(Priority.CRITICAL, 103_123_456, 1_239_876_543, 12, 40, 4, 1, 0b1_0101, "Baha na hangtod sa ikaduhang andana. " + "x".repeat(43))
    private val sosNoFix = SosRequest(Priority.INFO, null, null, 0, 0, 1, 0, 1 shl 15, "")
    private val location = Location(103_123_999, 1_239_876_000, 4, 1)

    private val ids = mapOf(
        "sos_max" to id(0x01), "sos_nofix" to id(0x02), "update" to id(0x03), "receipt" to id(0x04), "ack" to id(0x05),
    )

    @Tag("write-vectors")
    @Test
    fun write() {
        val device = crypto.signKeypair(deviceSeed)
        val sign = crypto.signKeypair(signSeed)
        val box = crypto.boxKeypair(boxSeed)
        fun sos(name: String, req: SosRequest): Envelope = signedEnvelope(
            crypto, device.secretKey, Kind.SOS, ids.getValue(name), req.priority, T0, T0 + req.priority.ttlS,
            device.publicKey, keyId, crypto.seal(encodeSosPayload(req), box.publicKey),
        )
        fun server(name: String, kind: Kind, ref: Envelope, status: Int): Envelope = signedEnvelope(
            crypto, sign.secretKey, kind, ids.getValue(name), ref.priority, T0 + 60, ref.expiresAt, sign.publicKey, keyId,
            le(ByteArray(EnvelopeCodec.SERVER_BODY)).put(ref.msgId.bytes).put(status.toByte()).putInt((T0 + 60).toInt()).array(),
        )
        val max = sos("sos_max", sosMax)
        val noFix = sos("sos_nofix", sosNoFix)
        val update = signedEnvelope(
            crypto, device.secretKey, Kind.UPDATE, ids.getValue("update"), max.priority, T0 + 30, max.expiresAt,
            device.publicKey, keyId, max.msgId.bytes + crypto.seal(encodeLocation(location), box.publicKey),
        )
        val lines = linkedMapOf(
            "device_seed" to deviceSeed,
            "device_sign_pub" to device.publicKey,
            "server_key_id" to byteArrayOf(keyId.toByte()),
            "server_sign_seed" to signSeed,
            "server_sign_pub" to sign.publicKey,
            "server_box_seed" to boxSeed,
            "server_box_pub" to box.publicKey,
            "server_box_secret" to box.secretKey,
            "sos_max" to max.bytes,
            "sos_max_plaintext" to encodeSosPayload(sosMax),
            "sos_nofix" to noFix.bytes,
            "sos_nofix_plaintext" to encodeSosPayload(sosNoFix),
            "update" to update.bytes,
            "update_plaintext" to encodeLocation(location),
            "receipt" to server("receipt", Kind.RECEIPT, max, 0).bytes,
            "ack" to server("ack", Kind.ACK, max, AckStatus.ACKNOWLEDGED.ordinal).bytes,
        )
        file.parentFile.mkdirs()
        file.writeText(
            "# Taptap envelope v1 golden vectors. Generated by GoldenVectorsTest.write; do not edit by hand.\n" +
                "# TEST KEYS ONLY: derived from public fixed seeds. Never use them on a real server.\n" +
                "# All times: created_at = $T0 (server events at +60 s). Format: name=hex\n" +
                lines.entries.joinToString("") { (k, v) -> "$k=${v.toHex()}\n" },
        )
    }

    @Test
    fun `vectors decode, verify and open to the fixed inputs`() {
        val v = file.readLines().filter { '=' in it && !it.startsWith("#") }
            .associate { it.substringBefore('=') to it.substringAfter('=').hexBytes() }
        fun env(name: String): Envelope = assertNotNull(EnvelopeCodec.decode(v.getValue(name)), name)

        val device = crypto.signKeypair(v.getValue("device_seed"))
        val sign = crypto.signKeypair(v.getValue("server_sign_seed"))
        val box = crypto.boxKeypair(v.getValue("server_box_seed"))
        assertContentEquals(device.publicKey, v.getValue("device_sign_pub"))
        assertContentEquals(sign.publicKey, v.getValue("server_sign_pub"))
        assertContentEquals(box.publicKey, v.getValue("server_box_pub"))
        assertContentEquals(box.secretKey, v.getValue("server_box_secret"))

        for (name in ids.keys) {
            val e = env(name)
            assertEquals(ids.getValue(name), e.msgId, name)
            assertEquals(keyId, e.keyId)
            assertEquals(0, e.hops)
            assertContentEquals(if (e.kind.fromServer) sign.publicKey else device.publicKey, e.senderKey, name)
            assertTrue(verifySignature(crypto, e), "$name signature")
        }

        val max = env("sos_max")
        assertEquals(269, max.bytes.size, "the max SOS envelope")
        for ((name, req) in listOf("sos_max" to sosMax, "sos_nofix" to sosNoFix)) {
            val e = env(name)
            val plain = assertNotNull(crypto.openSealed(e.body, box.publicKey, box.secretKey), name)
            assertContentEquals(v.getValue("${name}_plaintext"), plain)
            assertEquals(req, decodeSosPayload(e.priority, plain))
            assertEquals(T0 + req.priority.ttlS, e.expiresAt)
        }
        val update = env("update")
        assertEquals(max.msgId, update.refMsgId)
        val loc = crypto.openSealed(update.body.copyOfRange(16, update.body.size), box.publicKey, box.secretKey)
        assertEquals(location, decodeLocation(assertNotNull(loc)))
        for (name in listOf("receipt", "ack")) {
            assertEquals(max.msgId, env(name).refMsgId)
            assertEquals(T0 + 60, env(name).createdAt)
        }
    }
}
